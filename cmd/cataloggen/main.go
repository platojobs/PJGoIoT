// Command cataloggen 从 internal/devicecatalog 的唯一真值表生成设备类型目录迁移。
//
// 用法（在仓库根目录）：
//
//	go run ./cmd/cataloggen
//
// 生成文件：
//   - db/migrations/000015_device_type_catalog.up.sql
//   - db/migrations/000015_device_type_catalog.down.sql
//
// 不要手改这两个文件；改目录内容请修改 internal/devicecatalog/catalog.go 后重新运行。
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"

	"github.com/platojobs/PJGoIoT/internal/devicecatalog"
)

const (
	versionDir = "db/migrations"
	upPath     = "db/migrations/000015_device_type_catalog.up.sql"
	downPath   = "db/migrations/000015_device_type_catalog.down.sql"
)

func main() {
	if err := os.MkdirAll(versionDir, 0o755); err != nil {
		log.Fatalf("创建迁移目录失败: %v", err)
	}
	if err := os.WriteFile(upPath, []byte(renderUp()), 0o644); err != nil {
		log.Fatalf("写入 %s 失败: %v", upPath, err)
	}
	if err := os.WriteFile(downPath, []byte(renderDown()), 0o644); err != nil {
		log.Fatalf("写入 %s 失败: %v", downPath, err)
	}
	fmt.Printf("已生成 %s 与 %s（%d 个设备类型）\n", filepath.Base(upPath), filepath.Base(downPath), len(devicecatalog.Types()))
}

func renderUp() string {
	var b bytes.Buffer
	b.WriteString("-- Code generated by go run ./cmd/cataloggen; DO NOT EDIT.\n")
	b.WriteString("-- 000015：设备类型目录（服务端事实来源，供两端 App 的产品/市场模块读取）。\n")
	b.WriteString("--\n")
	b.WriteString("-- 取舍说明：\n")
	b.WriteString("--   * 新建 device_type_catalog 而不是复用旧 device_types：旧表服务于历史 /device-types 接口，\n")
	b.WriteString("--     新表字段与 /catalog/device-types 响应一一对应，避免为了新增 metrics/limitations 改动旧契约。\n")
	b.WriteString("--   * 版本号放在单行 device_type_catalog_meta 并在每次管理端写入时自增，ETag 直接由版本号派生，\n")
	b.WriteString("--     因此内容相同的 PUT 也会让 ETag 变化（客户端能感知到一次管理动作）。\n")
	b.WriteString("--   * 软删除用 deleted_at；列表查询过滤已删除项，管理端可再次 PUT 恢复。\n")
	b.WriteString("--   * 访问记录按 (user_id, catalog_version) 去重，只用于后续灰度，不影响匿名读取。\n\n")

	b.WriteString(`CREATE TABLE device_type_catalog (
    type text PRIMARY KEY CHECK (type ~ '^[a-z][a-z0-9_]*$'),
    display_name text NOT NULL,
    description text NOT NULL DEFAULT '',
    gatt_services jsonb NOT NULL DEFAULT '[]'::jsonb,
    metrics jsonb NOT NULL DEFAULT '[]'::jsonb,
    limitations jsonb NOT NULL DEFAULT '[]'::jsonb,
    compatibility jsonb NOT NULL DEFAULT '{}'::jsonb,
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz
);

CREATE INDEX device_type_catalog_live_idx ON device_type_catalog (type) WHERE deleted_at IS NULL;

CREATE TABLE device_type_catalog_meta (
    id smallint PRIMARY KEY,
    version bigint NOT NULL CHECK (version > 0),
    updated_at timestamptz NOT NULL DEFAULT now()
);

INSERT INTO device_type_catalog_meta (id, version, updated_at) VALUES (1, 1, now());

CREATE TABLE device_type_catalog_audits (
    id bigserial PRIMARY KEY,
    device_type text NOT NULL,
    action text NOT NULL CHECK (action IN ('upsert', 'delete')),
    actor text NOT NULL,
    catalog_version bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX device_type_catalog_audits_type_idx ON device_type_catalog_audits (device_type, created_at DESC, id DESC);

CREATE TABLE device_type_catalog_accesses (
    user_id uuid NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    catalog_version bigint NOT NULL,
    first_accessed_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, catalog_version)
);

`)

	types := devicecatalog.Types()
	b.WriteString("INSERT INTO device_type_catalog\n")
	b.WriteString("    (type, display_name, description, gatt_services, metrics, limitations, compatibility, updated_at)\n")
	b.WriteString("VALUES\n")
	for i, t := range types {
		compat := mustJSON(t.Compatibility)
		services := mustJSON(t.GATTServices)
		metrics := mustJSON(t.Metrics)
		limitations := mustJSON(t.Limitations)
		fmt.Fprintf(&b,
			"    (%s, %s, %s, %s::jsonb, %s::jsonb, %s::jsonb, %s::jsonb, now())",
			quote(t.Type), quote(t.DisplayName), quote(t.Description),
			quote(services), quote(metrics), quote(limitations), quote(compat),
		)
		if i == len(types)-1 {
			b.WriteString(";\n")
		} else {
			b.WriteString(",\n")
		}
	}
	return b.String()
}

func renderDown() string {
	return `-- Code generated by go run ./cmd/cataloggen; DO NOT EDIT.
DROP TABLE IF EXISTS device_type_catalog_accesses;
DROP TABLE IF EXISTS device_type_catalog_audits;
DROP TABLE IF EXISTS device_type_catalog_meta;
DROP TABLE IF EXISTS device_type_catalog;
`
}

func mustJSON(v any) string {
	raw, err := json.Marshal(v)
	if err != nil {
		log.Fatalf("序列化目录 JSON 失败: %v", err)
	}
	return string(raw)
}

func quote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", "''") + "'"
}
